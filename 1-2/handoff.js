/* 과학탐구실험1 Ⅰ-2 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js(worked.js) 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "<b>귀납적 탐구</b>: 여러 개별 관찰에서 공통된 규칙을 이끌어 낸다. 예) 열두 밤의 관찰 → ‘8초 동안 우는 횟수 + 5 ≈ 기온(°C)’",
  "귀납으로 얻은 규칙은 <b>관찰한 범위 안에서만</b> 믿을 만하고, 새로운 관찰(13 °C 아래에서는 울지 않음)이 나오면 고쳐진다.",
  "두 변인(우는 횟수와 기온)의 관계는 점을 찍어 본 <b>산점도</b>에서 규칙이 드러났다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「연역적 탐구와 변인 통제」에서는 귀납과 <b>반대 방향</b>(가설 → 예측 → 시험)으로 탐구하고, 03 「데이터 시각화」에서는 두 변인의 관계를 보여 주는 <b>산점도</b>가 다시 나옵니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], D01[1], "이 이야기의 <b>연역적 탐구</b>는 방향이 반대입니다. 먼저 가설을 세우고, ‘가설이 옳다면 이렇게 될 것’이라는 예측을 실험으로 시험합니다."],
  check: {
    q: "여러 밤의 관찰을 모아 ‘우는 횟수 + 5 ≈ 기온’이라는 규칙을 얻었다. 어떤 탐구 방법일까?",
    options: ["귀납적 탐구", "연역적 탐구", "모형 실험"],
    a: 0,
    why: "개별 관찰에서 일반 규칙을 이끌어 냈으니 귀납이다. 연역은 가설에서 예측을 이끌어 내 시험한다."
  }
});

/* 03 ← 01 */
window.sthBridge({
  ep: "ep3", need: "01", doneKey: "ep1",
  lines: [D01[2], "이 이야기에서는 질문에 맞는 그래프를 고릅니다. <b>관계는 산점도</b>, 시간에 따른 변화는 선그래프, 전체에 대한 비율은 원그래프, 범주별 비교는 막대그래프입니다."],
  check: {
    q: "기온과 귀뚜라미가 우는 횟수처럼 두 변인의 관계를 보려면 어떤 그래프가 알맞을까?",
    options: ["원그래프", "막대그래프", "산점도", "그래프 없이 표만"],
    a: 2,
    why: "두 수치 변인을 가로·세로에 놓고 점을 찍으면 관계(규칙)가 드러난다."
  }
});
})();
